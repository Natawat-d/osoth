"use client";
// เนื้อหา "หนังสือข้อตกลงในการใช้บริการและยินยอมทำหัตถการเสริมความงาม" — ตามเอกสารคลินิก 7 ข้อ
// ใช้ 2 ที่: modal เซ็นบนจอ (iPad) ในหน้า OPD + หน้าพิมพ์ /app/consent-form
import { thaiDocDate, ageFromBirth } from "@/lib/healthItems";

const U = ({ v, w = "auto" }) => (
  <span className="ca-u" style={{ minWidth: w }}>{v || " "}</span>
);

// customer: object ลูกค้า (อาจ null) · procedure: ชื่อหัตถการ/คอร์ส · company: บริษัท · date: YYYY-MM-DD
// signature / doctorSignature: dataURL (แสดงเหนือเส้นเซ็น) — ไม่มีก็เว้นให้เซ็นบนกระดาษ
// doctorName: ชื่อแพทย์ (ถ้ามี)
export default function ConsentAgreement({ customer: c, procedure, company, date, signature, doctorSignature, doctorName }) {
  const dt = thaiDocDate(date || new Date().toISOString().slice(0, 10));
  const fullName = c ? `${c.prefix ? c.prefix + " " : ""}${c.full_name || ""} ${c.sure_name || ""}`.trim() : "";
  const bd = c?.birth_date ? c.birth_date.split("-") : null;
  const clinicName = company?.name || "คลินิก";

  return (
    <div className="ca-doc" style={{ fontSize: 13.5, lineHeight: 1.95 }}>
      <div className="text-center fw-bold mb-1" style={{ fontSize: 15.5 }}>
        หนังสือข้อตกลงในการใช้บริการและยินยอมทำหัตถการเสริมความงาม
      </div>
      <div className="text-end">วันที่ <U v={dt.d} w={34} /> เดือน <U v={dt.m} w={90} /> ปี <U v={dt.y} w={52} /></div>

      <div style={{ textIndent: 36 }}>
        โดยหนังสือฉบับนี้ ข้าพเจ้า (นาย/นาง/นางสาว) <U v={fullName} w={220} />
        &nbsp;วัน/เดือน/ปีเกิด: <U v={bd ? `${bd[2]} / ${bd[1]} / ${+bd[0] + 543}` : ""} w={110} />
        &nbsp;อายุ: <U v={ageFromBirth(c?.birth_date)} w={36} /> ปี
      </div>
      <div>
        เลขบัตรประชาชน/หนังสือเดินทาง: <U v={c?.id_card} w={180} />
        &nbsp;ที่อยู่ปัจจุบัน: <U v={c?.address} w={300} />
      </div>
      <div>ข้าพเจ้าตกลงใช้บริการและยินยอมทำหัตถการ: <U v={procedure} w={380} /></div>

      <div style={{ textIndent: 36 }}>
        โดยข้าพเจ้าเป็นผู้ใช้บริการของ <b>{clinicName}</b> ได้ตกลงยินยอมรับเงื่อนไขของทางคลินิกดังต่อไปนี้
      </div>

      <ol className="ps-3 mb-2" style={{ listStyle: "none" }}>
        <li className="mb-1" style={{ textIndent: 20 }}>
          1. ผู้ใช้บริการมีสิทธิยกเลิกบริการภายในระยะเวลา 7 วัน นับจากวันที่ได้ชำระเงินค่าบริการ และผู้ใช้บริการไม่ได้ใช้บริการตามที่ตกลงกันไว้
          ผู้ให้บริการ/คลินิกจะดำเนินการคืนเงินให้แก่ผู้ใช้บริการเต็มจำนวน กรณีชำระเงินผ่านช่องทางที่มีค่าธรรมเนียมเพิ่มเติม
          ผู้ใช้บริการเป็นผู้รับผิดชอบค่าธรรมเนียมแต่เพียงผู้เดียว ดังนี้หากพ้นระยะเวลาที่กำหนดแล้วหรือไม่ใช่ความผิดของผู้ให้บริการ/คลินิก
          ผู้ใช้บริการไม่สามารถขอเงินคืนหรือเปลี่ยนหรือแลกโปรแกรมไม่ว่ากรณีใด ๆ ทั้งสิ้น
        </li>
        <li className="mb-1" style={{ textIndent: 20 }}>
          2. ข้าพเจ้าได้รับคำอธิบายถึงรายละเอียดขั้นตอนของการรักษาและการทำหัตถการเสริมความงาม ทางเลือก ประโยชน์ ความเสี่ยง ผลข้างเคียง
          และภาวะแทรกซ้อนที่อาจเกิดขึ้นได้ รวมถึงความจำเป็นของการรักษาและการทำหัตถการ ข้อดีและข้อเสีย
          รวมทั้งระยะเวลาการพักฟื้นและการดูแลตนเองภายหลังการรักษาและการทำหัตถการดังกล่าวจากผู้ให้บริการและแพทย์
          จนเป็นที่เข้าใจและมีโอกาสซักถามข้อสงสัยอย่างเพียงพอแล้ว
          <div style={{ textIndent: 20 }} className="mt-1">
            โดยภาวะแทรกซ้อนที่อาจเกิดขึ้นในขณะ ระหว่าง และหลังการรักษาและการทำหัตถการเสริมความงาม ได้แก่ อาการแพ้ ผื่นแดง การติดเชื้อ
            ผิวหนังมีสีเปลี่ยนแปลงไป เกิดแผลหรือแผลเป็น เกิดรอยฟกช้ำ ปวดศีรษะ ปวด บวม เจ็บหรือคันบนใบหน้าหรือบริเวณที่มีการฉีดยาหรือให้สารน้ำต่าง ๆ
            รอยจากเข็มฉีดยา คิ้วหรือหนังตาตก กล้ามเนื้ออ่อนแรงเฉพาะที่ สารเติมเต็มหรือฟิลเลอร์เคลื่อนตัวจากบริเวณที่ทำการรักษาหรือทำหัตถการ
            มีก้อนเกิดขึ้นใต้ผิวหนัง ลิ่มเลือดอุดกั้นในปอด สูญเสียการมองเห็น เนื้อเยื่อตาย ความพิการ อาจถึงแก่ชีวิต
            หรือภาวะแทรกซ้อนทางการแพทย์อื่น ๆ ที่อาจเกิดขึ้นได้
          </div>
        </li>
        <li className="mb-1" style={{ textIndent: 20 }}>
          3. ข้าพเจ้ายืนยันว่า ได้ศึกษาข้อมูลเกี่ยวกับการรักษาและการทำหัตถการดังกล่าว รวมทั้งได้สอบถามข้อมูลจากแพทย์และผู้ให้บริการจนเข้าใจอย่างครบถ้วน
          ตัดสินใจเข้ารับบริการด้วยความสมัครใจ ไม่ได้ถูกบังคับ ข่มขู่ หรือถูกหลอกลวง และได้เปิดเผยข้อมูลสุขภาพ โรคประจำตัว ประวัติการแพ้ยา การใช้ยา
          การตั้งครรภ์ รวมถึงข้อมูลทางการแพทย์อื่นที่เกี่ยวข้องอย่างครบถ้วนและเป็นความจริง
        </li>
        <li className="mb-1" style={{ textIndent: 20 }}>
          4. ข้าพเจ้ารับทราบและเข้าใจว่า การรักษาและการทำหัตถการเสริมความงามมีความเสี่ยงหรือมีผลข้างเคียงหรืออาจมีภาวะแทรกซ้อนทางการแพทย์ที่เกิดขึ้นได้
          แม้ผู้ให้บริการ/คลินิกและแพทย์จะได้ให้การบริการด้วยความระมัดระวังตามมาตรฐานวิชาชีพเวชกรรมแล้ว
          โดยไม่ได้มีความผิดพลาดหรือประมาทเลินเล่อก็ตาม อีกทั้งผลการรักษาอาจแตกต่างกันไปตามสภาพร่างกายและการตอบสนองของแต่ละบุคคล
          และปัจจัยเฉพาะของผู้ใช้บริการ ซึ่งผู้ให้บริการ/คลินิกหรือแพทย์จึงไม่อาจรับรองหรือรับประกันผลลัพธ์ให้เป็นไปตามความคาดหวัง
          หรือความพึงพอใจของผู้ใช้บริการได้ในทุกกรณี
        </li>
        <li className="mb-1" style={{ textIndent: 20 }}>
          5. ข้าพเจ้าทราบดีว่า ในระหว่างการรักษาและการทำหัตถการ อาจเกิดสภาวะที่ไม่อาจคาดการณ์ได้และอาจจำเป็นต้องมีการเปลี่ยนแปลงการรักษา
          และการทำหัตถการซึ่งไม่ตรงกับการรักษาและการทำหัตถการที่ได้ตกลงกันไว้ ข้าพเจ้าขอมอบอำนาจให้ผู้ให้บริการ/คลินิก แพทย์ ทีมงาน
          หรือผู้ได้รับมอบหมายที่เกี่ยวข้อง ดำเนินการรักษา การทำหัตถการ หรือส่งตัวไปยังสถานพยาบาลอื่น ภายใต้การใช้วิจารณญาณทางวิชาชีพ
          โดยคำนึงถึงความปลอดภัยและผลการรักษาของข้าพเจ้าเป็นหลัก รวมถึงสภาวะอื่นใดที่จำเป็นเร่งด่วนที่ต้องได้รับการรักษาแก้ไข
          โดยที่ผู้ให้บริการ/คลินิกและแพทย์ไม่ทราบมาก่อนที่จะทำการรักษาและทำหัตถการ
        </li>
        <li className="mb-1" style={{ textIndent: 20 }}>
          6. ข้าพเจ้ารับทราบว่า การปฏิบัติตามคำแนะนำของแพทย์ ทั้งก่อนและหลังการรักษา การรับประทานยา การมาตรวจติดตามผลตามนัด
          และการแจ้งอาการผิดปกติอย่างทันท่วงที เป็นส่วนสำคัญที่มีผลต่อประสิทธิภาพของการรักษา หากข้าพเจ้าไม่ปฏิบัติตามคำแนะนำดังกล่าว
          อาจส่งผลให้ผลการรักษาไม่เป็นไปตามที่คาดหวัง หรือเกิดภาวะแทรกซ้อนเพิ่มเติมได้
        </li>
        <li className="mb-1" style={{ textIndent: 20 }}>
          7. ข้าพเจ้ายินยอมให้ผู้ให้บริการ/คลินิก เก็บ รวบรวม ใช้ และเปิดเผยข้อมูลส่วนบุคคลของข้าพเจ้า ได้แก่ ชื่อ-นามสกุล
          เลขบัตรประชาชนหรือข้อมูลระบุตัวตน ข้อมูลการติดต่อ ประวัติการรักษา ประวัติสุขภาพ ข้อมูลการรับบริการ เวชระเบียน
          และข้อมูลอื่นที่เกี่ยวข้องกับการให้บริการ การรักษาและทำหัตถการเสริมความงาม เพื่อวัตถุประสงค์ในการลงทะเบียน ติดต่อ ให้บริการ ตรวจรักษา
          ทำหัตถการ ติดตามผลการรักษา บันทึกประวัติเวชระเบียน ในกรณีที่ข้อมูลดังกล่าวเป็นข้อมูลสุขภาพหรือข้อมูลส่วนบุคคลที่มีความอ่อนไหว
          ข้าพเจ้ายินยอมให้ผู้ให้บริการ/คลินิกเก็บ รวบรวม ใช้ และเปิดเผยข้อมูลดังกล่าวเท่าที่จำเป็นเพื่อวัตถุประสงค์ในการให้บริการ
          การรักษาและทำหัตถการเสริมความงามให้ข้าพเจ้า
        </li>
      </ol>

      <div style={{ textIndent: 36 }}>
        ข้าพเจ้าตกลงและเข้าใจข้อตกลงในการใช้บริการและยินยอมทำหัตถการเสริมความงามตามรายละเอียดข้างต้น
        และขอรับรองว่ามีสติสัมปชัญญะดีทุกประการ จึงลงลายมือชื่อไว้เป็นหลักฐาน
      </div>

      <div className="text-end mt-2">
        <span className="border border-dark rounded px-3 py-1 fw-bold">HN. {c?.HN_number || "…………………"}</span>
      </div>

      <div className="row mt-3 text-center" style={{ lineHeight: 1.7 }}>
        <div className="col-6">
          {signature
            ? <img src={signature} alt="ลายเซ็นลูกค้า" style={{ height: 58, display: "block", margin: "0 auto" }} />
            : <div style={{ height: 44 }} />}
          <div>ลงชื่อ ……………………………… ผู้ให้ความยินยอม/ผู้ใช้บริการ</div>
          <div>( {fullName || "………………………………………"} )</div>
        </div>
        <div className="col-6">
          {doctorSignature
            ? <img src={doctorSignature} alt="ลายเซ็นแพทย์" style={{ height: 58, display: "block", margin: "0 auto" }} />
            : <div style={{ height: 44 }} />}
          <div>ลงชื่อ ……………………………… แพทย์</div>
          <div>( {doctorName || "………………………………………"} ) ว. …………</div>
        </div>
      </div>

      <style jsx global>{`
        .ca-u { display: inline-block; border-bottom: 1px dotted #888; padding: 0 6px; font-weight: 600; }
      `}</style>
    </div>
  );
}
